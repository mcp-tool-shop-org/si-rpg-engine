    view[at + 1] = body.y;
    view[at + 2] = body.z;
    view[at + 3] = body.vx;
    view[at + 4] = body.vy;
    view[at + 5] = body.vz;
    view[at + 6] = body.qx;
    view[at + 7] = body.qy;
    view[at + 8] = body.qz;
    view[at + 9] = body.qw;
    view[at + 10] = body.wx;
    view[at + 11] = body.wy;
    view[at + 12] = body.wz;
    view[at + 13] = body.hx;
